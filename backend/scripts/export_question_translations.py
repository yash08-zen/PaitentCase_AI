"""
scripts/export_question_translations.py
---------------------------------------
Regenerate frontend/src/utils/i18n_questions.js (offline fallback for the
interview question texts) from the backend source of truth
(app/data/translations.py + translations_complaint.py).

Usage (from backend/):
  .\\.venv312\\Scripts\\python.exe scripts\\export_question_translations.py
"""
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from app.data.translations import QUESTION_TRANSLATIONS  # noqa: E402

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "frontend", "src", "utils", "i18n_questions.js"))


def main() -> None:
    data = {
        key: {lang: {k: v for k, v in entry.items() if k in ("text", "help", "choices") and v}
              for lang, entry in langs.items()}
        for key, langs in QUESTION_TRANSLATIONS.items()
    }
    body = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/**\n * src/utils/i18n_questions.js\n * GENERATED by backend/scripts/export_question_translations.py from\n"
                " * backend/app/data/translations*.py. Do not edit by hand.\n */\n\n")
        f.write(f"export const LOCAL_QUESTION_TRANSLATIONS = {body};\n")
    print(f"Wrote {len(data)} questions to {OUT}")


if __name__ == "__main__":
    main()
